    public GRPBrowser(WOWBrowser parent, boolean modal, BFDataFileClass bfdfc, BFGRPChunk grp) {
        super(parent, modal);
        this.bfdfc = bfdfc;
        this.grp = grp;
        initComponents();
        ArrayList grpElems;
        if (grp != null && grp.getGrpGaoList() != null) {
            grpElems = grp.getGrpGaoList();
            setTitle("Group browser: Group elem count: " + grpElems.size());
            Iterator i = grpElems.iterator();
            TreeMap<Integer, BFKeyListElem> tm;
            lmGRPGAOList.clear();
            while (i.hasNext()) {
                tm = (TreeMap<Integer, BFKeyListElem>) (i.next());
                lmGRPGAOList.addElement(((BFKeyListElem)(tm.firstEntry().getValue())).getParseHandler());
            }
        }
    }

