    private void lGameObjectsValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lGameObjectsValueChanged
        if (lGameObjects.getSelectedIndex() != -1 && r.getGaos() != null && r.getGaos().size() > lGameObjects.getSelectedIndex()) {
            BFGaoChunk gao = r.getGaos().get(lGameObjects.getSelectedIndex());
            if (gao.isBoundingBoxDebugEnabled()) {
                btBBoxHide.setEnabled(true);
                btBBoxShow.setEnabled(false);
            } else {
                btBBoxHide.setEnabled(false);
                btBBoxShow.setEnabled(true);
            }
            if (gao.getGlobalMatrix() == null) {
                return;
            }
            Vector3 v = gao.getGlobalMatrix().getPos();
            Vector3 v2 = new Vector3();
            v2.set(v);
            Vector3.transformVector(v2, new Matrix4x4(r.getRotationMatrix()), v2);
            tfX.setText("" + v2.getX());
            tfY.setText("" + v2.getY());
            tfZ.setText("" + v2.getZ());
        }
    }//GEN-LAST:event_lGameObjectsValueChanged

    private void btBBoxShowActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btBBoxShowActionPerformed
        if (lGameObjects.getSelectedIndex() != -1 && r.getGaos() != null && r.getGaos().size() > lGameObjects.getSelectedIndex()) {
            BFGaoChunk gao = r.getGaos().get(lGameObjects.getSelectedIndex());
            gao.setBoundingBoxDebugEnabled(true);
            lGameObjectsValueChanged(null);

        }
    }//GEN-LAST:event_btBBoxShowActionPerformed

    private void btBBoxHideActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btBBoxHideActionPerformed
        if (lGameObjects.getSelectedIndex() != -1 && r.getGaos() != null && r.getGaos().size() > lGameObjects.getSelectedIndex()) {
            BFGaoChunk gao = r.getGaos().get(lGameObjects.getSelectedIndex());
            gao.setBoundingBoxDebugEnabled(false);
            lGameObjectsValueChanged(null);
        }
    }//GEN-LAST:event_btBBoxHideActionPerformed

    private void btGotoNoHideActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btGotoNoHideActionPerformed
        float x, y, z;
        try {
            x = Float.parseFloat(tfX.getText());
            y = Float.parseFloat(tfY.getText());
            z = Float.parseFloat(tfZ.getText());
        } catch (Exception e) {
            return;
        }
        r.setPosition(new Vector3(x, y, z));
    }//GEN-LAST:event_btGotoNoHideActionPerformed

