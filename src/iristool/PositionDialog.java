    public void setGaoList(ArrayList<BFGaoChunk> gaos) {
        lmGameObjects.clear();
        Iterator i = gaos.iterator();
        while (i.hasNext()) {
            BFGaoChunk gao = (BFGaoChunk) (i.next());
            lmGameObjects.addElement(gao.getGaoName());
        }
    }

