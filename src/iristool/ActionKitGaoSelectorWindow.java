    private void btOkActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btOkActionPerformed
        if (lActionKitGaoList.getSelectedIndex() == -1 || actionKitGaos == null || 
                actionKitGaos.size() <= lActionKitGaoList.getSelectedIndex() || actionKitGaos.get(lActionKitGaoList.getSelectedIndex()) == null) return;
        r.setAniPlaying(false);
        if (r.getSelectedSingleGao() != null) {
            BFGaoChunk actionGao = actionKitGaos.get(lActionKitGaoList.getSelectedIndex());
            BFKeyListElem kle = new BFKeyListElem(actionGao.getActionsKey(), BFActionListChunk.class, false);
            kle.setParseHandler((BFChunkParseInterface)(actionGao.getActionListChunkKLE().getParseHandler()));
            r.getSelectedSingleGao().setActionListChunkKLE(kle); ///
            r.getSelectedSingleGao().setActionsKey(actionKitGaos.get(lActionKitGaoList.getSelectedIndex()).getActionsKey());
            r.setAniGao(r.getSelectedSingleGao()); // it needed because of action list check, anigao previously was null
            bpapw.populateActionList(r.getAnigao());
        }
                
        this.dispose();
    }//GEN-LAST:event_btOkActionPerformed

