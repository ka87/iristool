    public ActionKitGaoSelectorWindow(RendererControlsWindow parent, boolean modal, BFWOWChunk bfwc, Renderer r) {
        super(parent, modal);
        this.bpapw = parent;
        this.bfwc = bfwc;
        this.r = r;
        initComponents();
        actionKitGaos.clear();
        BFGaoListChunk bfglc = bfwc.getGaoList();
        Iterator i = bfglc.getGaos().iterator();
        TreeMap<Integer, BFKeyListElem> el;
        BFGaoChunk gao;
        while (i.hasNext()) {
            el = (TreeMap<Integer, BFKeyListElem>) i.next();
            if (el != null) {
                gao = (BFGaoChunk)(((BFKeyListElem)(el.firstEntry().getValue())).getParseHandler());
                if (gao != null && (gao.getFlags() & 2) != 0 && gao.getActionsKey() != 0 && gao.getActionsKey() != -1) {
                    actionKitGaos.add(gao);
                    lmActionKitGaoList.addElement(gao);
                }
            }
        }
    }

