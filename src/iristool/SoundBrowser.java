    private void btPlayActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btPlayActionPerformed
        byte data[] = null;

        if (isPlaying) {
            if (line != null) {
                line.stop();
                return;
            }
        }

        int sel = lSoundList.getSelectedIndex();
        if (sel == -1) {
            return;
        }
        if (soundBankType == BFDataFileClass.BF_D_SOUNDBANK_HEADER_COLLECTION) {
            BFFatTableElem bfe = bfc.getFatTable().getElemByKey(keys[sel]);
            if (bfe == null) {
                JOptionPane.showMessageDialog(this, "Key not found in fat table.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            data = BFClass.extractFatTableElem(bfc, bfc.getFatTable().getElemIndex(bfe), true);
        }
        if (wfis != null && wfis.length > sel && wfis[sel] != null) {
            WaveFormatInterface wfi = wfis[sel];

            if (wfi.getFormat() != 2) {
                JOptionPane.showMessageDialog(this, "Audio format is not MS ADPCM (used in PC version of BGAE), so I can not play it.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            byte convertedData[];
            if (soundBankType == BFDataFileClass.BF_D_SOUNDBANK_HEADER_COLLECTION) {
                ByteBuffer bb = ByteBuffer.wrap(data);
                bb.position(wfi.getHeaderSize());
                convertedData = SoundConverter.convertToPCM(bb, wfi.getNumChannels(), wfi.getBlockAlign());
            } else {
                if (flags == null || flags.length <= sel) {
                    return;
                }
                if (flags[sel] == 8) {
                    data = bfc.getDataFromBFbyKey(keys[sel]);
                    if (data == null) {
                        JOptionPane.showMessageDialog(this, "Key not found in fat table.", "Error", JOptionPane.ERROR_MESSAGE);
                        return;
                    }
                    ByteBuffer bb = ByteBuffer.wrap(data);
                    bb.position(wfi.getHeaderSize());
                    convertedData = SoundConverter.convertToPCM(bb, wfi.getNumChannels(), wfi.getBlockAlign());
                } else {
                    convertedData = SoundConverter.convertToPCM(ByteBuffer.wrap(wfi.getData()), wfi.getNumChannels(), wfi.getBlockAlign());
                }
            }

            AudioFormat af = new AudioFormat(wfi.getSampleRate(), 16, wfi.getNumChannels(), true, false);
            DataLine.Info info = new DataLine.Info(SourceDataLine.class, af);
            try {
                line = (SourceDataLine) AudioSystem.getLine(info);
                line.open(af, 16384);
                line.start();
                line.addLineListener(new LineListener() {
                    @Override
                    public void update(LineEvent le) {
                        if (le.getType().equals(LineEvent.Type.STOP)) {
                            line.removeLineListener(this);
                            line.close();
                            isPlaying = false;
                            updatePlayButtonString();
                            line = null;
                        }
                    }
                });
                isPlaying = true;
                updatePlayButtonString();
                Thread thread = new Thread() {
                    @Override
                    public void run() {
                        line.write(convertedData, 0, convertedData.length);
                        line.drain();
                        line.stop();
                    }
                };

                thread.setPriority(Thread.MAX_PRIORITY);
                thread.start();

            } catch (LineUnavailableException ex) {
                line = null;
                JOptionPane.showMessageDialog(this, "Line Unavailable Exception: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btPlayActionPerformed

    private String selectDirAndGetPath() {
        JFileChooser jfc = new JFileChooser();
        jfc.setFileSelectionMode(JFileChooser.DIRECTORIES_ONLY);

        if (jfc.showSaveDialog(this) == JFileChooser.APPROVE_OPTION) {
            return jfc.getSelectedFile().getAbsolutePath();
        }
        return null;
    }

    private void btSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btSaveActionPerformed
        int sel = lSoundList.getSelectedIndex();
        if (sel == -1) {
            return;
        }
        if (wfis != null && wfis.length > sel) {
            WaveFormatInterface wfi = wfis[sel];
            String path = selectDirAndGetPath();
            if (path == null) {
                return;
            }
            try (FileOutputStream fos = new FileOutputStream(String.format("%s%s%x.wav", path,
                    File.separator, keys[sel]))) {
                if (soundBankType == BFDataFileClass.BF_D_SOUNDBANK_PACK
                        && flags != null && flags.length > sel && flags[sel] != 8) {
                    fos.write(wfi.getAssembledWavData());
                } else {
                    byte data[] = bfc.getDataFromBFbyKey(keys[sel]);
                    if (data == null) {
                        throw new Exception("Key not found in fat table.");
                    }
                    fos.write(data);
                }
                fos.close();
                JOptionPane.showMessageDialog(this, "Save succeded.", "Information", JOptionPane.INFORMATION_MESSAGE);
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Save error. Exception: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btSaveActionPerformed

    private void btSaveAllActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btSaveAllActionPerformed
        String path = selectDirAndGetPath();
        if (path == null) {
            return;
        }
        for (int i = 0; i < keys.length; i++) {
            try (FileOutputStream fos = new FileOutputStream(String.format("%s%s%x.wav", path,
                    File.separator, keys[i]))) {
                if (soundBankType == BFDataFileClass.BF_D_SOUNDBANK_PACK
                        && flags != null && flags.length > i && flags[i] != 8) {
                    fos.write(wfis[i].getAssembledWavData());
                } else {
                    byte data[] = bfc.getDataFromBFbyKey(keys[i]);
                    if (data == null) {
                        throw new Exception("Key not found in fat table.");
                    }
                    fos.write(data);
                }
                fos.close();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Save error. Exception: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }
        if (keys.length > 0) {
            JOptionPane.showMessageDialog(this, "Save succeded.", "Information", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btSaveAllActionPerformed

    private void lSoundListValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lSoundListValueChanged
        taWAVInfo.setText("");
        if (hxWAVData != null) {
            hxWAVData.setByteContent(new byte[]{});
        }
        if (hxWAVUnkData != null) {
            hxWAVUnkData.setByteContent(new byte[]{});
        }
        if (hxWAVExtraData != null) {
            hxWAVExtraData.setByteContent(new byte[]{});
        }
        int sel = lSoundList.getSelectedIndex();
        if (sel == -1) {
            return;
        }
        if (wfis != null && wfis.length > sel && wfis[sel] != null) {
            taWAVInfo.setText(wfis[sel].toString());
            if (wfis[sel].getWaveData() != null) {
                if (hxWAVData != null) {
                    hxWAVData.setByteContent(wfis[sel].getWaveData());
                }
            }
            if (wfis[sel].getUnk2Data() != null) {
                if (hxWAVUnkData != null) {
                    hxWAVUnkData.setByteContent(wfis[sel].getUnk2Data());
                }
            }
            if (wfis[sel].getUnk1Data() != null) {
                if (hxWAVExtraData != null) {
                    hxWAVExtraData.setByteContent(wfis[sel].getUnk1Data());
                }
            }
        }
        this.pack();
    }//GEN-LAST:event_lSoundListValueChanged

