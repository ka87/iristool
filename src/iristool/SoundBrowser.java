    public SoundBrowser(java.awt.Frame parent, boolean modal, BFClass bfc, BFDataFileClass bfdfc, int soundBankType) {
        super(parent, modal);
        this.bfc = bfc;
        this.bfdfc = bfdfc;
        this.soundBankType = soundBankType;
        initComponents();
        if (!IrisToolDefines.PUBLIC_RELEASE) {
            hxWAVData = new HexLib(new byte[]{});
            hxWAVUnkData = new HexLib(new byte[]{});
            hxWAVExtraData = new HexLib(new byte[]{});
            hxWAVData.setHexBeanEditable(false);
            hxWAVUnkData.setHexBeanEditable(false);
            hxWAVExtraData.setHexBeanEditable(false);
            pWAVData.add(hxWAVData);
            pWAVUnkData.add(hxWAVUnkData);
            pWAVExtraData.add(hxWAVExtraData);
        } else {
            btSave.setEnabled(false);
            btSaveAll.setEnabled(false);
        }
        this.pack();

        lmSoundList.clear();

        if (soundBankType == BFDataFileClass.BF_D_SOUNDBANK_PACK) {
            keys = bfdfc.getParsedSoundBankPack().getKeys();
            flags = bfdfc.getParsedSoundBankPack().getFlags();
            wfis = bfdfc.getParsedSoundBankPack().getWfis();

            if (keys != null && flags != null && wfis != null) {
                for (int i = 0; i < keys.length; i++) {
                    lmSoundList.addElement(String.format("Key: %x, Flags: 0x%x%s - Length: %.2f secs", keys[i], flags[i],
                            (flags[i] == 8 ? " [Not embedded]" : ""), wfis[i].getSoundLengthInSecs()));
                }
            }
        } else if (soundBankType == BFDataFileClass.BF_D_SOUNDBANK_HEADER_COLLECTION) {
            keys = bfdfc.getParsedSoundBankHeaderCollection().getActiveLanguageSpecificSoundKeys();
            int keysDef[] = bfdfc.getParsedSoundBankHeaderCollection().getDefaultSoundKeys();
            wfis = bfdfc.getParsedSoundBankHeaderCollection().getWfis();

            String fn;
            if (keys != null && wfis != null) {
                for (int i = 0; i < keys.length; i++) {
                    fn = _getFileNameFromBF(keys[i]);
                    fn = (fn == null ? "" : " (" + fn + ")");
                    lmSoundList.addElement(String.format("Key [active]: %x%s [Default Key: %x] - Length: %.2f secs", keys[i], fn, keysDef[i],
                            (wfis[i] != null ? wfis[i].getSoundLengthInSecs() : 0.0f)));
                }
            }
        }

    }

    private String _getFileNameFromBF(int key) {
        String fn = null;
        if (IrisToolDefines.isReadFileNameListAndDirectoryList()) {
            BFFatTableElem kle = bfc.getFatTable().getElemByKey(key);
            if (kle != null) {
                int idx = bfc.getFatTable().getElemIndex(kle);
                BFFilenameElem fne = bfc.getFatTable().getFileNameElemByIndex(idx);
                fn = fne.getFileName();
            }
        }
        return fn;
    }

