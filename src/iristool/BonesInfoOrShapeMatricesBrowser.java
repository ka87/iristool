    public BonesInfoOrShapeMatricesBrowser(WOWBrowser parent, boolean modal, BFDataFileClass bfdfc, BFGaoChunk gao) {
        super(parent, modal);
        this.bfdfc = bfdfc;
        this.gao = gao;
        initComponents();
        setTitle("Bones Info / Shape Matrices browser");
        ArrayList boneShapes;
        lmMultiPartElemList.clear();
        if (gao != null) {
            if ((gao.getFlags() & 0x1000000) != 0) {
                boneShapes = gao.getBoneShapes();
                if (boneShapes != null) {
                    Iterator it = boneShapes.iterator();
                    BoneShapeElem bse;
                    BFKeyListElem kle;
                    BFGaoChunk subgao;
                    int i = 0;
                    while (it.hasNext()) {
                        bse = (BoneShapeElem) it.next();
                        kle = bse.getBoneGaoChunkKLE();
                        Integer id = null;
                        id = bse.getBoneID();
                        if (kle != null) {
                            if (kle.getParseHandler() instanceof BFGaoChunk) {
                                subgao = (BFGaoChunk) kle.getParseHandler();
                                lmMultiPartElemList.addElement("GAO: " + subgao.getGaoName() + ((id != null) ? (", Element ID: " + id) : ""));
                            } else {
                                lmMultiPartElemList.addElement("BUG: Not a GAO" + ((id != null) ? (", Element ID: " + id) : ""));
                            }
                        } else {
                            lmMultiPartElemList.addElement("No GAO" + ((id != null) ? (", Element ID: " + id) : ""));
                        }

                        i++;
                    }
                }
            } else {
                if (gao.getBoneShapeMatrices() != null) {
                    ArrayList<Matrix4x4> mtxal = gao.getBoneShapeMatrices();
                    Iterator it = mtxal.iterator();
                    while (it.hasNext()) {
                        Matrix4x4 mtx = (Matrix4x4) it.next();
                        lmMultiPartElemList.addElement(mtx);
                    }
                }
            }
        }
    }

